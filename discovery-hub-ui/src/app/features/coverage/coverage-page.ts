import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { DatePipe, DecimalPipe } from '@angular/common';
import { describeError } from '../../core/api/api-error';
import { CoverageApi } from '../../core/api/coverage-api';
import { CoverageMetric, CoverageModule, CoverageReport } from '../../core/models/coverage';
import { AgoPipe } from '../../shared/pipes/format.pipes';
import { Empty, ErrorBand, Loading } from '../../shared/ui/state-blocks';

/** Bands used to colour a percentage. Mirrors JaCoCo's own red/amber/green. */
type CoverageBand = 'low' | 'medium' | 'high';

/**
 * Test coverage per service and across the whole repository.
 *
 * The numbers come from `public/coverage-summary.json`, generated by
 * `infrastructure/coverage-report.sh`. It is a static asset rather than an API
 * response: coverage describes the source tree at the moment the suites ran,
 * not the state of a running service, so no service exposes it and none was
 * changed to add this screen.
 *
 * A stale report is therefore possible. The generation timestamp is shown
 * prominently for exactly that reason — an unlabelled coverage number invites
 * the reader to assume it is current.
 */
@Component({
  selector: 'app-coverage-page',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [DatePipe, DecimalPipe, AgoPipe, Loading, Empty, ErrorBand],
  templateUrl: './coverage-page.html',
  styles: `
    .cov-provenance {
      display: flex;
      flex-wrap: wrap;
      align-items: center;
      gap: 0.5rem 0.9rem;
      margin-bottom: 1rem;
      font-size: 0.85rem;
    }

    .cov-tag {
      padding: 0.15rem 0.5rem;
      border-radius: 999px;
      border: 1px solid transparent;
      font-size: 0.75rem;
      font-weight: 600;
    }

    .cov-tag--high {
      background: var(--color-success-bg);
      color: var(--color-success-fg);
      border-color: var(--color-success-border);
    }

    .cov-tag--medium {
      background: var(--color-amber-bg);
      color: var(--color-amber-fg);
      border-color: var(--color-amber-border);
    }

    /* Red / amber / green at the same thresholds JaCoCo's own report uses, so
       the two do not contradict each other in the drill-down. */
    .cov-value--low { color: var(--color-danger-fg); font-weight: 600; }
    .cov-value--medium { color: var(--color-amber-fg); font-weight: 600; }
    .cov-value--high { color: var(--color-success-fg); font-weight: 600; }

    .cov-bar--low { background: var(--color-danger); }
    .cov-bar--medium { background: var(--color-amber-fg); }
    .cov-bar--high { background: var(--color-success); }

    .cov-card { margin-top: 1rem; }
    .cov-note { margin: 0.6rem 0 0; }

    .cov-cell { min-width: 11rem; }
    .cov-cell__head { margin-bottom: 0.3rem; gap: 0.5rem; }

    .cov-detail > td { background: var(--color-surface-muted); }
    .cov-detail__body { padding: 0.4rem 0 0.8rem; }
    .cov-detail__head { margin-bottom: 0.6rem; }

    .cov-extras {
      margin: 0 0 0.9rem;
      padding: 0.6rem 0.8rem;
      background: var(--color-surface);
      border: 1px solid var(--color-border);
      border-radius: var(--radius-md);
    }

    /* The nested table sits inside a row of the outer one, so it needs its own
       surface to stay legible against the tinted detail row. */
    .cov-packages {
      background: var(--color-surface);
      border: 1px solid var(--color-border);
      border-radius: var(--radius-md);
      overflow: hidden;
    }

    .cov-pre {
      margin: 0;
      padding: 0.7rem 0.9rem;
      background: var(--color-surface-muted);
      border: 1px solid var(--color-border);
      border-radius: var(--radius-md);
      font-family: var(--font-mono);
      font-size: 0.78rem;
      line-height: 1.6;
      overflow-x: auto;
    }
  `,
})
export class CoveragePage {
  private readonly coverage = inject(CoverageApi);

  protected readonly report = signal<CoverageReport | null>(null);
  protected readonly loading = signal(true);
  protected readonly error = signal<string | null>(null);

  /** Module whose package breakdown is expanded, or null for none. */
  protected readonly expanded = signal<string | null>(null);

  protected readonly modules = computed(() => this.report()?.modules ?? []);

  /**
   * Modules with no report on disk. Called out separately because missing and
   * zero are different facts: a module that was never run is not a module with
   * no tests, and rendering it as 0% would libel it.
   */
  protected readonly missing = computed(() =>
    this.modules().filter((module) => !module.available),
  );

  protected readonly measured = computed(() => this.modules().filter((module) => module.available));

  /** True when any suite reported a failing test, which makes coverage suspect. */
  protected readonly hasFailures = computed(() => (this.report()?.overall.tests.failed ?? 0) > 0);

  constructor() {
    this.load();
  }

  protected load(): void {
    this.loading.set(true);
    this.coverage.report().subscribe({
      next: (report) => {
        this.report.set(report);
        this.error.set(null);
        this.loading.set(false);
      },
      error: (error: unknown) => {
        this.error.set(describeError(error));
        this.report.set(null);
        this.loading.set(false);
      },
    });
  }

  protected toggle(moduleId: string): void {
    this.expanded.update((current) => (current === moduleId ? null : moduleId));
  }

  protected isExpanded(moduleId: string): boolean {
    return this.expanded() === moduleId;
  }

  /**
   * Red below 50, amber below 80, green at or above it.
   *
   * Deliberately not configurable: a threshold a reader can move is not a
   * threshold, and these match the convention JaCoCo's own HTML report uses so
   * the two do not disagree when someone opens the drill-down.
   */
  protected band(pct: number): CoverageBand {
    if (pct < 50) {
      return 'low';
    }
    return pct < 80 ? 'medium' : 'high';
  }

  /** The metrics a module reports that only its own toolchain produces. */
  protected extras(module: CoverageModule): { name: string; metric: CoverageMetric }[] {
    return Object.entries(module.extra).map(([name, metric]) => ({ name, metric }));
  }

  protected uncovered(metric: CoverageMetric): number {
    return metric.total - metric.covered;
  }
}
